for grp, sel in (('figshare', [s for s in subs if s.startswith('s') and not s.startswith('sub-')]), ('OSF', [s for s in subs if s.startswith('sub-')])):
    ks = [s for s in sel if 'ERP_1.6_asr' in old.get(s, {}) and 'ERP_1.6_asr' in new.get(s, {})]
    L.append(f"{grp} & {len(ks)} & {np.mean([old[s]['ERP_1.6_none'] for s in ks]):.3f} & {np.mean([old[s]['ERP_1.6_asr'] for s in ks]):.3f} & {np.mean([new[s]['ERP_1.6_asr'] for s in ks]):.3f}\\\\\n")
L.append("\\br\n\\end{tabular}\n\\end{indented}\n\\end{table}\nPer participant, direct ASR produced output energy between 1 and $10^{18}$ times the input on the OSF participants with interpolated bad channels (sub-22: $6.8\\times 10^{18}$; sub-23: 2.0); the rank-safe variant restores energy ratios below 1.\n")

# ---- S5 folds
L.append(r"""\section*{S5. Held-out parameter selection}
""")
L.append(f"Halves (seed 20261004): A = {', '.join(H['halves'][0])}; B = {', '.join(H['halves'][1])}.\n\n")
for fam, lab in (('nlms', 'NLMS step size $\\mu$'), ('cca', 'CCA threshold $r$')):
    h = H[fam]
    L.append(f"\\emph{{{lab}}}: selection scores on A = {{{', '.join(f'{k}: {v:.2f}' for k, v in h['fold1']['scores'].items())}}} (chosen {h['fold1']['chosen']}); on B = {{{', '.join(f'{k}: {v:.2f}' for k, v in h['fold2']['scores'].items())}}} (chosen {h['fold2']['chosen']}); held-out objective {h['heldout_objective']:.2f} points vs in-sample {h['insample_objective']:.2f}.\n\n")
L.append(f"\\emph{{Gate threshold $\\theta$}} (balanced accuracy of per-second decisions): fold 1 scores {{{', '.join(f'{k}: {v:.3f}' for k, v in HG['fold1']['scores_on_selection_half'].items())}}} (chosen {HG['fold1']['chosen']}; held-out balanced accuracy {HG['fold1']['heldout_balanced_acc']:.3f}, sensitivity {HG['fold1']['heldout_sens']:.3f}, specificity {HG['fold1']['heldout_spec']:.3f}); fold 2 scores {{{', '.join(f'{k}: {v:.3f}' for k, v in HG['fold2']['scores_on_selection_half'].items())}}} (chosen {HG['fold2']['chosen']}; held-out {HG['fold2']['heldout_balanced_acc']:.3f}, {HG['fold2']['heldout_sens']:.3f}, {HG['fold2']['heldout_spec']:.3f}).\n")

# ---- S6/S7 surrogate stats
for fam, title, lab in (('F6 controls vs true reference (reg)', 'S6. Surrogate references vs true reference, regression (F6)', 's6'), ('F7 controls vs true reference (NLMS)', 'S7. Surrogate references vs true reference, gated NLMS (F7)', 's7')):
    L.append(f"\\section*{{{title}}}\n{{\\footnotesize\n\\begin{{longtable}}{{@{{}}llllrr}}\n\\caption{{\\label{{tab:{lab}}}Surrogate minus true reference: mean [95\\% CI]; improved/worsened(/tied); unadjusted and Holm $p$ (24 tests).}}\\\\\n\\br\nCondition & Surrogate & Mean [95\\% CI] & Up/down(/tied) & $p$ & Holm\\\\\n\\mr\n\\endfirsthead\n\\br\nCondition & Surrogate & Mean [95\\% CI] & Up/down(/tied) & $p$ & Holm\\\\\n\\mr\n\\endhead\n")
    for r in S[fam]:
        L.append(f"{r['task']} {r['speed']} ({r['n']}) & {tex_esc(r['b'])} & {row(r)}\\\\\n")
