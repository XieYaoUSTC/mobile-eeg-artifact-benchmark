# ---- S9 gate per participant + transition
per = {}
for seg in C['gate_segments']:
    per.setdefault(seg['sub'], {'m': [], 's': []})
    (per[seg['sub']]['m'] if seg['moving'] else per[seg['sub']]['s']).append(seg['gate_on_frac'])
L.append(r"""\section*{S9. Motion gate per participant and transition test}
\begin{table}[h]
\caption{\label{tab:s9}Causal gate ($\theta=100$): fraction of per-second decisions with the gate open, averaged over each participant's locomotion segments and standing segments.}
\begin{indented}
\item[]\small
\begin{tabular}{@{}lcc@{\hspace{2em}}lcc}
\br
Participant & locomotion & standing & Participant & locomotion & standing\\
\mr
""")
ks = sorted(per)
half = (len(ks) + 1) // 2
for i in range(half):
    a = ks[i]; b = ks[i + half] if i + half < len(ks) else None
    fa = lambda s: (f"{np.mean(per[s]['m']):.2f}" if per[s]['m'] else '--', f"{np.mean(per[s]['s']):.2f}" if per[s]['s'] else '--')
    ma, sa = fa(a)
    if b:
        mb, sb = fa(b); L.append(f"{a} & {ma} & {sa} & {b} & {mb} & {sb}\\\\\n")
    else:
        L.append(f"{a} & {ma} & {sa} & & & \\\\\n")
g = C['gate']['per_second_decisions']
ts = C['transition_summary']
L.append(f"\\br\n\\end{{tabular}}\n\\end{{indented}}\n\\end{{table}}\nPooled per-second decisions against the segment speed label: TP {g['TP']:.0f}, FN {g['FN']:.0f}, FP {g['FP']:.0f}, TN {g['TN']:.0f}; sensitivity {C['gate']['sensitivity']:.3f}, specificity {C['gate']['specificity']:.3f}. Transition test (standing and 1.6\\,m/s SSVEP recordings concatenated, $n={ts['switch_delay_s']['n']}$): gate switch delay {ts['switch_delay_s']['mean']:.2f}\\,s (SD {ts['switch_delay_s']['sd']:.2f}); gate-open fraction while standing {ts['gate_on_frac_standing']['mean']:.3f}, while walking {ts['gate_on_frac_walking']['mean']:.3f}; standing samples altered {ts['standing_altered_frac']['mean']*100:.1f}\\%; SSVEP accuracy standing {ts['ssvep_standing_none']['mean']:.1f}\\% $\\rightarrow$ {ts['ssvep_standing_gated']['mean']:.1f}\\%, walking {ts['ssvep_walking_none']['mean']:.1f}\\% $\\rightarrow$ {ts['ssvep_walking_gated']['mean']:.1f}\\% (paired change $-2.65$ [$-7.50$, $+0.61$], 8/7/7, $p=0.85$).\n")

